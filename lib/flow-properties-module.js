(function (global) {
  // One org-level Flow module, "FlowProperties", with read access to every Custom LU imported from
  // Flow properties. Built from Flow's own code generator output per LU projection: the shared
  // helpers once, then per LU only the readable `<Entity>Set` and the declarations it references.
  const MODULE_NAME = "FlowProperties";
  const SIGNATURE = "FlowProperties module generated by NovacuraBuddy";
  // Last shared declaration in Flow's generator output (build 115548); everything after it is
  // projection-specific.
  const PRELUDE_END = "GetTypeMismatchErrorMessage";

  const beginMarker = (lu) => `// >>> FlowProperties: ${lu}`;
  const endMarker = (lu) => `// <<< FlowProperties: ${lu}`;

  const DECLARATION = /^ ?(?:private\s+)?(?:type|function|let)\s+([A-Za-z_][A-Za-z0-9_]*)/;
  const COMMENT = /^(?:\/\/|\/\*\*|\s\*)/;

  /** Splits FlowScript into top-level declarations; comment lines directly above one belong to it. */
  function splitDeclarations(code) {
    const chunks = [{ name: null, lines: [] }];
    for (const line of String(code).replace(/\r\n?/g, "\n").split("\n")) {
      const match = line.match(DECLARATION);
      if (match) {
        const current = chunks[chunks.length - 1];
        const comments = [];
        while (current.lines.length && COMMENT.test(current.lines[current.lines.length - 1])) comments.unshift(current.lines.pop());
        chunks.push({ name: match[1], lines: [...comments, line] });
      } else {
        chunks[chunks.length - 1].lines.push(line);
      }
    }
    return chunks
      .map((c) => ({ name: c.name, text: c.lines.join("\n").replace(/\s+$/, "") }))
      .filter((c) => c.text.trim());
  }

  const identifiers = (text) => new Set(text.match(/[A-Za-z_][A-Za-z0-9_]*/g) || []);

  /** From one projection's generated module: the shared prelude and the code `setName` needs. */
  function extractReadSet(generatedCode, setName) {
    const withoutHeader = String(generatedCode).replace(/^\s*\/\*[\s\S]*?#importSource[\s\S]*?\*\/\s*/, "");
    const chunks = splitDeclarations(withoutHeader);
    const end = chunks.findIndex((c) => c.name === PRELUDE_END);
    if (end < 0) throw new Error(`Flow's code generator output has no ${PRELUDE_END} — the FlowProperties builder needs an update.`);
    const prelude = chunks.slice(0, end + 1).map((c) => c.text).join("\n\n");
    const own = chunks.slice(end + 1).filter((c) => c.name);
    if (!own.some((c) => c.name === setName)) throw new Error(`The generated module has no ${setName}.`);

    const byName = new Map(own.map((c) => [c.name, c]));
    const needed = new Set([setName]);
    const queue = [setName];
    while (queue.length) {
      for (const id of identifiers(byName.get(queue.shift()).text)) {
        if (byName.has(id) && !needed.has(id)) { needed.add(id); queue.push(id); }
      }
    }
    return { prelude, code: own.filter((c) => needed.has(c.name)).map((c) => c.text).join("\n\n") };
  }

  /** The LU blocks of a FlowProperties module, in file order. */
  function parseBlocks(source) {
    const blocks = [];
    const re = /^\/\/ >>> FlowProperties: (\S+)\n([\s\S]*?)\n\/\/ <<< FlowProperties: \1$/gm;
    for (const m of String(source).replace(/\r\n?/g, "\n").matchAll(re)) blocks.push({ lu: m[1], code: m[2] });
    return blocks;
  }

  const isOurs = (source) => String(source).includes(SIGNATURE);

  /** Merges `blocks` ([{lu, code}]) into `existingSource` (null for a new module): same-LU blocks are
   *  replaced in place, new ones appended, the prelude is the fresh one. A declaration another LU
   *  already defines identically is dropped; a different one with the same name rejects that LU. */
  function mergeModule({ existingSource, prelude, blocks, stamp }) {
    if (existingSource && existingSource.trim() && !isOurs(existingSource)) {
      throw new Error(`A ${MODULE_NAME} module exists but was not made by NovacuraBuddy — rename or delete it in Flow; nothing was changed.`);
    }
    const merged = existingSource ? parseBlocks(existingSource) : [];
    const conflicts = [];
    const included = [];
    for (const block of blocks) {
      const others = merged.filter((b) => b.lu !== block.lu);
      const defined = new Map(others.flatMap((b) => splitDeclarations(b.code).filter((c) => c.name).map((c) => [c.name, c.text])));
      const own = splitDeclarations(block.code);
      const clash = own.find((c) => c.name && defined.has(c.name) && defined.get(c.name) !== c.text);
      if (clash) {
        conflicts.push({ lu: block.lu, message: `${clash.name} is already declared differently by another LU in ${MODULE_NAME}.` });
        continue;
      }
      const code = own.filter((c) => !(c.name && defined.has(c.name))).map((c) => c.text).join("\n\n");
      const at = merged.findIndex((b) => b.lu === block.lu);
      if (at >= 0) merged[at] = { lu: block.lu, code };
      else merged.push({ lu: block.lu, code });
      included.push(block.lu);
    }
    const header = [
      "/*",
      `${SIGNATURE}: read access to the Custom LUs imported from Flow properties.`,
      `Updated ${stamp}. Code between the ">>> FlowProperties:" and "<<< FlowProperties:" markers is replaced on the next import.`,
      "*/"
    ].join("\n");
    const body = merged.map((b) => `${beginMarker(b.lu)}\n${b.code}\n${endMarker(b.lu)}`).join("\n\n");
    return { source: `${header}\n${prelude}\n\n${body}\n`, included, conflicts, lus: merged.map((b) => b.lu) };
  }

  /** Generates each LU's code, merges it into the existing module and commits once. A failing LU is
   *  reported and left out; nothing is committed when no LU made it.
   *  deps: generate(lu) -> {code, setName}; readExisting() -> {asset, source} | null;
   *  commit(source, asset | null) -> asset; now() -> text */
  async function updateFlowPropertiesModule({ luNames, generate, readExisting, commit, now }) {
    const blocks = [];
    const failed = [];
    let prelude = null;
    for (const lu of luNames) {
      try {
        const { code, setName } = await generate(lu);
        const part = extractReadSet(code, setName);
        prelude = part.prelude;
        blocks.push({ lu, code: part.code });
      } catch (err) {
        failed.push({ lu, message: err.message });
      }
    }
    if (!blocks.length) return { included: [], failed, lus: [] };
    const existing = await readExisting();
    const merged = mergeModule({ existingSource: existing && existing.source, prelude, blocks, stamp: now() });
    failed.push(...merged.conflicts);
    if (!merged.included.length) return { included: [], failed, lus: [] };
    await commit(merged.source, existing && existing.asset);
    return { included: merged.included, failed, lus: merged.lus };
  }

  const api = { MODULE_NAME, splitDeclarations, extractReadSet, parseBlocks, mergeModule, isOurs, updateFlowPropertiesModule };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  if (typeof global !== "undefined") global.FlowPropertiesModule = api;
})(typeof window !== "undefined" ? window : globalThis);
